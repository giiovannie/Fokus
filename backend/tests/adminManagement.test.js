it('descarta la bandeja propia y permite próximos avisos sin tocar los eventos', async () => {
  vi.spyOn(NotificationPreference, 'findOne').mockResolvedValue(null)
  const tomorrow = new Date(Date.now() + 86400000).toISOString().slice(0, 10)
  vi.spyOn(Task, 'findAll').mockResolvedValue([{ id: 1, title: 'Entrega', due_date: tomorrow, subject: { name: 'Materia' } }])
  vi.spyOn(Exam, 'findAll').mockResolvedValue([]); vi.spyOn(StudyActivity, 'findAll').mockResolvedValue([])
  const dismissed = []
  vi.spyOn(NotificationDismissal, 'bulkCreate').mockImplementation(async rows => { dismissed.push(...rows) })
  vi.spyOn(NotificationDismissal, 'findAll').mockImplementation(async ({ where }) => dismissed.filter(row => row.user_id === where.user_id))
  const before = await auth(request(app).get('/api/notifications'), 7)
  expect(before.body).toHaveLength(1)
  expect((await auth(request(app).delete('/api/notifications'), 7)).status).toBe(204)
  expect(dismissed[0]).toMatchObject({ user_id: 7, notification_key: before.body[0].id })
  expect((await auth(request(app).get('/api/notifications'), 7)).body).toEqual([])
  Task.findAll.mockResolvedValue([{ id: 2, title: 'Nueva entrega', due_date: tomorrow, subject: { name: 'Materia' } }])
  expect((await auth(request(app).get('/api/notifications'), 7)).body).toHaveLength(1)
})
