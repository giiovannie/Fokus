it('pagina, filtra y ordena sin devolver hashes, incluso si el ORM los incluye accidentalmente', async () => {
  vi.spyOn(User, 'findAndCountAll').mockResolvedValue({ count: 101, rows: [{ ...accounts.get(7), profile: { nickname: 'Estudiante' } }] })
  const result = await auth(request(app).get('/api/admin/users?page=2&limit=10&search=7&status=active&sort=email&direction=ASC'))
  expect(result.status).toBe(200)
  expect(result.body).toMatchObject({ page: 2, limit: 10, total: 101, totalPages: 11 })
  expect(result.body.users[0]).toMatchObject({ id: 7, username: 'Estudiante', status: 'active' })
  expect(JSON.stringify(result.body)).not.toMatch(/password|hash/)
  expect(User.findAndCountAll).toHaveBeenCalledWith(expect.objectContaining({ offset: 10, limit: 10, where: expect.objectContaining({ status: 'active' }) }))
  expect((await auth(request(app).get('/api/admin/users?limit=101'))).status).toBe(400)
  expect((await auth(request(app).get('/api/admin/users?sort=password'))).status).toBe(400)
})
